import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import fs from "node:fs";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Monolith — FootPrintStudio
*/
`;

const prod = process.argv[2] === "production";

/** Concatenate module CSS into the BRAT styles.css artifact. */
function writeStyles() {
	const parts = [
		"/* Monolith — bundled module styles */\n",
		fs.readFileSync("packages/epochs/styles.css", "utf8"),
		"\n",
		fs.readFileSync("packages/grimoire/styles.css", "utf8"),
		"\n",
		fs.readFileSync("packages/visage/styles.css", "utf8"),
		"\n",
		fs.readFileSync("src/styles-host.css", "utf8"),
	];
	fs.writeFileSync("styles.css", parts.join("\n"));
}

writeStyles();

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	loader: {
		".md": "text",
	},
	alias: {
		"@monolith/epochs": path.resolve("packages/epochs/src/module.ts"),
		"@monolith/grimoire": path.resolve("packages/grimoire/src/module.ts"),
		"@monolith/visage": path.resolve("packages/visage/src/module.ts"),
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
